package com.trackNest.trackNest_App.members.entity;

import com.trackNest.trackNest_App.business.entity.BusinessEntity;
import com.trackNest.trackNest_App.members.MembershipPlan;
import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.OnDelete;
import org.hibernate.annotations.OnDeleteAction;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.Date;
import java.util.UUID;

@Entity
@Builder
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@ToString
@Table(
        name = "member_entity",
        uniqueConstraints =
                {
                        @UniqueConstraint(
                                name = "uk_businessId_email",
                                columnNames = {
                                        "business_entity_id", "email"
                                }),
                        @UniqueConstraint(
                                name = "uk_businessId_phone",
                                columnNames = {
                                        "business_entity_id", "phone"
                                }
                        ),
                        @UniqueConstraint(
                                name = "uk_businessId_memberIdOfBusiness",
                                columnNames = {
                                        "business_entity_id", "memberId_ofBusiness"
                                }
                        )
                }
)
public class MemberEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
            name = "business_entity_id",
            foreignKey = @ForeignKey(name = "fk_member_business")
    )
    @OnDelete(action = OnDeleteAction.CASCADE)
    private BusinessEntity businessEntity;
    @Column(nullable = false)
    private String fullName;
   // @Column(unique = true)
    private String email;
   // @Column(unique = true)
    private String memberId_ofBusiness;
    @Column(nullable = false)
    private BigDecimal membership_fee;
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private MembershipPlan membershipPlan;
    private String member_code_AutoGenerated;
    //@Column(unique = true)
    private String phone;
    private String address;
    private Date date_of_birth;
    private String gender ;
    private Date membership_start;
    private Date membership_end;
    private String status ;
    private String emergency_contact_name;
    private String emergency_contact_phone;
    private String notes;
    private LocalDateTime createdAt;
    private LocalDateTime updatedAt;
    private  String createdBy;
    private  String updatedBy;
}
