@Service
public class MemberService {

    private final MemberRepository memberRepository;
    private final BusinessService businessService;
    private final MemberBulkImportService memberBulkImportService;

    public MemberService(MemberRepository memberRepository, BusinessService businessService, MemberBulkImportService memberBulkImportService) {
        this.memberRepository = memberRepository;
        this.businessService = businessService;
        this.memberBulkImportService = memberBulkImportService;
    }

    public boolean existsByIdAndBusinessEntity_IdAndBusinessEntity_UserEntity_Id
            (UUID memberId, UUID businessId, UUID ownerId) {
        return  memberRepository.existsByIdAndBusinessEntity_IdAndBusinessEntity_UserEntity_Id
                (memberId, businessId, ownerId);
    }
    public MemberResponseDto saveMember(MemberRequestDto memberRequestDto, UUID businessId) {
        if (businessId == null) {
            throw new BusinessNotFound("Business id is null");
        }
        BusinessEntity be = businessService.getBusinessByBusinessId(businessId);
        if (be == null) {
            throw new BusinessNotFound("Business Not Found");
        }
        MemberEntity memberEntity = memberRepository.save(
                MemberEntity.builder()
                        .businessEntity(be)
                        .email(memberRequestDto.getEmail())
                        .address(memberRequestDto.getAddress())
                        .createdAt(LocalDateTime.now())
                        .memberId_ofBusiness(memberRequestDto.getMemberId_ofBusiness())
                        .membership_fee(memberRequestDto.getMembership_fee())
                        .createdBy(be.getUser().getEmail())
                        .date_of_birth(memberRequestDto.getDate_of_birth())
                        .emergency_contact_name(memberRequestDto.getEmergency_contact_name())
                        .emergency_contact_phone(memberRequestDto.getEmergency_contact_phone())
                        .fullName(memberRequestDto.getFullName())
                        .gender(memberRequestDto.getGender())
                        .member_code_AutoGenerated(memberRequestDto.getMember_code_AutoGenerated())
                        .membership_end(memberRequestDto.getMembership_end())
                        .membership_start(memberRequestDto.getMembership_start())
                        .membershipPlan(memberRequestDto.getMembershipPlan())
                        .phone(memberRequestDto.getPhone())
                        .status(memberRequestDto.getStatus())
                        .notes(memberRequestDto.getNotes())
                        .updatedAt(LocalDateTime.now())
                        .updatedBy(be.getUser().getEmail()).build()
        );
        return MemberResponseDto.builder()
                .member_id(memberEntity.getId())
                .member_name(memberEntity.getFullName())
                .businessId(be.getId())
                .created_at(memberEntity.getCreatedAt()).build();
    }

    public MemberResponseDto updateMember(MemberRequestDto memberRequestDto, UUID memberId) {
        if (memberRequestDto.getBusinessId() == null || memberId == null) {
            throw new MemberNotFound("Invalid memberId or businessId");
        }
        MemberEntity memberEntity = memberRepository.findMemberEntityById(memberId);
        if (memberEntity == null) {
            throw new MemberNotFound("Member Not Found");
        }
        memberEntity.setEmail(memberRequestDto.getEmail());
        if (memberRequestDto.getMembership_fee() != null) {
            memberEntity.setMembership_fee(memberRequestDto.getMembership_fee());
        }
        memberEntity.setAddress(memberRequestDto.getAddress());
        memberEntity.setGender(memberRequestDto.getGender());
        memberEntity.setMember_code_AutoGenerated(memberRequestDto.getMember_code_AutoGenerated());
        memberEntity.setMembership_end(memberRequestDto.getMembership_end());
        memberEntity.setMembership_start(memberRequestDto.getMembership_start());
        memberEntity.setMembershipPlan(memberRequestDto.getMembershipPlan());
        memberEntity.setPhone(memberRequestDto.getPhone());
        memberEntity.setStatus(memberRequestDto.getStatus());
        memberEntity.setNotes(memberRequestDto.getNotes());
        memberEntity.setUpdatedAt(LocalDateTime.now());

        MemberEntity updatedMemberEntity = memberRepository.save(memberEntity);
        return MemberResponseDto.builder().
                member_id(updatedMemberEntity.getId())
                .member_name(updatedMemberEntity.getFullName())
                .businessId(updatedMemberEntity.getBusinessEntity().getId())
                .created_at(updatedMemberEntity.getCreatedAt())
                .build();
    }

    public List<MemberResponseDto> findAllMembersByBusinessId(UUID businessId) {
        List<MemberResponseDto> memberResponseDtos = new ArrayList<>();
        if (businessId == null) {
            throw new BusinessNotFound("Business id is null");
        }
        List<MemberEntity> memberEntities = memberRepository.findAllByBusinessEntity_Id(businessId);
        if (memberEntities == null || memberEntities.isEmpty()) {
            throw new MemberNotFound("No Member Found");
        }
        for (MemberEntity me : memberEntities) {
            memberResponseDtos.add(
                    MemberResponseDto.builder()
                            .member_id(me.getId())
                            .member_name(me.getFullName())
                            .businessId(me.getBusinessEntity().getId())
                            .created_at(me.getCreatedAt())
                            .build()
            );
        }
        return memberResponseDtos;
    }

    public MemberResponseDto findMemberById(UUID memberId) {
        if (memberId == null) {
            throw new MemberNotFound("Member id is null");
        }
        MemberEntity memberEntity = memberRepository.findMemberEntityById(memberId);
        if (memberEntity == null) {
            throw new MemberNotFound("Member Not Found");
        }
        return MemberResponseDto.builder()
                .member_id(memberEntity.getId())
                .member_name(memberEntity.getFullName())
                .businessId(memberEntity.getBusinessEntity().getId())
                .created_at(memberEntity.getCreatedAt())
                .build();
    }

    public void  deleteMemberById(UUID memberId) {
        // Authorizatin req
        if (memberId == null) {
            throw new MemberNotFound("Member id is null");
        }
        MemberEntity memberEntity = memberRepository.findMemberEntityById(memberId);
        if (memberEntity == null) {
            throw new MemberNotFound("Member Not Found");
        }
         memberRepository.deleteById(memberId);
        return;
    }

    // ---- bulk import: analyze -> preview -> commit --------------------------------------------

    /** Step 1: read the file and tell the client its columns, the member fields, and a suggested mapping. */
    public ImportAnalyzeResponseDto analyzeImport(MultipartFile file, UUID businessId, UUID ownerId) {
        businessService.getOwnedBusiness(businessId, ownerId);
        ParsedTable table = memberBulkImportService.readFile(file);
        return memberBulkImportService.analyze(table);
    }

    /** Step 2: apply the user's mapping to the whole file and show what would happen, without saving anything. */
    public ImportPreviewResponseDto previewImport(MultipartFile file, UUID businessId,
                                                  Map<String, String> params, UUID ownerId) {
        businessService.getOwnedBusiness(businessId, ownerId);
        ParsedTable table = memberBulkImportService.readFile(file);
        ImportMapping mapping = memberBulkImportService.parseMapping(params, table);
        ImportPlan plan = memberBulkImportService.plan(table, mapping, existingKeys(businessId));
        return memberBulkImportService.preview(plan, mapping);
    }

    /**
     * Step 3: re-reads and re-validates the file (the preview is never trusted), then saves every valid,
     * non-duplicate row in one transaction. Invalid rows are skipped and reported, not silently dropped.
     */
    @Transactional
    public BulkImportMemberResponseDto bulkImportMembers(MultipartFile file, UUID businessId,
                                                         Map<String, String> params, UUID ownerId) {
        BusinessEntity be = businessService.getOwnedBusiness(businessId, ownerId);
        String ownerEmail = be.getUser().getEmail();
        ParsedTable table = memberBulkImportService.readFile(file);
        ImportMapping mapping = memberBulkImportService.parseMapping(params, table);
        ImportPlan plan = memberBulkImportService.plan(table, mapping, existingKeys(businessId));

        if (plan.valid().isEmpty()) {
            throw new InvalidFileException("No valid rows to import. Run the preview to see what needs fixing");
        }

        LocalDateTime now = LocalDateTime.now();
        List<MemberEntity> entities = new ArrayList<>();
        for (ConvertedRow row : plan.valid()) {
            ImportedMember m = row.member();
            entities.add(MemberEntity.builder()
                    .businessEntity(be)
                    .fullName(m.fullName())
                    .email(m.email())
                    .memberId_ofBusiness(m.memberIdOfBusiness())
                    .membershipPlan(m.membershipPlan())
                    .membership_fee(m.membershipFee())
                    .phone(m.phone())
                    .address(m.address())
                    .date_of_birth(m.dateOfBirth())
                    .gender(m.gender())
                    .membership_start(m.membershipStart())
                    .membership_end(m.membershipEnd())
                    .status(m.status())
                    .emergency_contact_name(m.emergencyContactName())
                    .emergency_contact_phone(m.emergencyContactPhone())
                    .notes(m.notes())
                    .createdAt(now)
                    .createdBy(ownerEmail)
                    .updatedAt(now)
                    .updatedBy(ownerEmail)
                    .build());
        }
        try {
            // flush inside the try so a unique-constraint clash surfaces here and not later at commit
            memberRepository.saveAllAndFlush(entities);
        } catch (DataIntegrityViolationException ex) {
            throw new DuplicateMemberException("Nothing was imported: a member ID, phone number or email in "
                    + "this file is already used by another member. Remove or change the duplicates and try again.");
        }

        List<Integer> failedRows = new ArrayList<>();
        for (RowIssue issue : plan.issues()) {
            failedRows.add(issue.rowNumber());
        }
        return BulkImportMemberResponseDto.builder()
                .totalRows(plan.totalRows())
                .successImport(entities.size())
                .failedImport(plan.issues().size())
                .duplicateSkipped(plan.duplicateCount())
                .failedRowsNumbers(failedRows)
                .rowErrors(memberBulkImportService.toRowErrors(plan.issues()))
                .errorsTruncated(memberBulkImportService.errorsTruncated(plan.issues()))
                .build();
    }

    private Set<String> existingKeys(UUID businessId) {
        Set<String> keys = new HashSet<>();
        for (MemberEntity me : memberRepository.findAllByBusinessEntity_Id(businessId)) {
            keys.addAll(DuplicateDetector.keysOf(me.getMemberId_ofBusiness(), me.getPhone(), me.getEmail()));
        }
        return keys;
    }
}
